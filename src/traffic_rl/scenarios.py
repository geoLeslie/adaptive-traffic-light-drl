"""Traffic demand scenarios with random (Poisson) arrivals.

Every vehicle is generated here in Python from a fixed seed and written to a route file as
an explicit <vehicle> with its own departure time and route. The same (scenario, seed)
therefore always produces the identical demand file, so every controller is evaluated on
exactly the same vehicles (plan: "Simpan berkas identik untuk setiap perbandingan").

Arrival model: per approach, a piecewise-constant rate (veh/h); inside each piece,
inter-arrival gaps are exponential, i.e. a Poisson process. Each vehicle then picks a
movement with probabilities TURN_SPLIT.
"""
from __future__ import annotations

import random
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

APPROACHES = ("N", "S", "E", "W")
EXIT = {  # (approach, movement) -> exit arm. Geometric left/right.
    ("N", "straight"): "S", ("N", "right"): "W", ("N", "left"): "E",
    ("S", "straight"): "N", ("S", "right"): "E", ("S", "left"): "W",
    ("E", "straight"): "W", ("E", "right"): "N", ("E", "left"): "S",
    ("W", "straight"): "E", ("W", "right"): "S", ("W", "left"): "N",
}
TURN_SPLIT = {"straight": 0.6, "left": 0.2, "right": 0.2}
ARRIVAL_END = 1800  # seconds of arrivals; the .sumocfg adds up to 600 s clearance

# A profile maps each approach to [(t_start, t_end, veh_per_hour), ...]
Profile = dict[str, list[tuple[float, float, float]]]


def _jitter(rng: random.Random, base: float) -> float:
    """Per-seed variation of +-15% so seeds within a scenario are not clones."""
    return base * rng.uniform(0.85, 1.15)


def balanced(rng: random.Random) -> Profile:
    return {a: [(0, ARRIVAL_END, _jitter(rng, 300))] for a in APPROACHES}


def unbalanced(rng: random.Random) -> Profile:
    busy = rng.choice([("N", "S"), ("E", "W")])
    return {a: [(0, ARRIVAL_END, _jitter(rng, 450 if a in busy else 150))] for a in APPROACHES}


def surge(rng: random.Random) -> Profile:
    """Steady base flow, then one approach surges in the middle of the episode."""
    hot = rng.choice(APPROACHES)
    start = rng.uniform(500, 800)
    end = start + 600
    prof: Profile = {}
    for a in APPROACHES:
        base = _jitter(rng, 250)
        if a == hot:
            prof[a] = [(0, start, base), (start, end, base + _jitter(rng, 500)), (end, ARRIVAL_END, base)]
        else:
            prof[a] = [(0, ARRIVAL_END, base)]
    return prof


def shift(rng: random.Random) -> Profile:
    """The dominant direction swaps halfway: NS busy then EW busy (or the reverse)."""
    first = rng.choice([("N", "S"), ("E", "W")])
    t = rng.uniform(800, 1000)
    prof: Profile = {}
    for a in APPROACHES:
        hi, lo = _jitter(rng, 450), _jitter(rng, 150)
        prof[a] = [(0, t, hi), (t, ARRIVAL_END, lo)] if a in first else [(0, t, lo), (t, ARRIVAL_END, hi)]
    return prof


def stress(rng: random.Random) -> Profile:
    """Demand near or above what the intersection can serve. Held out from training."""
    return {a: [(0, ARRIVAL_END, _jitter(rng, 480))] for a in APPROACHES}


SCENARIOS: dict[str, Callable[[random.Random], Profile]] = {
    "balanced": balanced,
    "unbalanced": unbalanced,
    "surge": surge,
    "shift": shift,
    "stress": stress,
}


@dataclass(frozen=True)
class Vehicle:
    vid: str
    depart: float
    approach: str
    movement: str


def generate_vehicles(
    scenario: str, seed: int, profile_fn: Callable[[random.Random], Profile] | None = None,
    turn_split: dict[str, float] | None = None,
) -> tuple[list[Vehicle], Profile]:
    # Seed mixes in the scenario name so "surge seed 5" and "shift seed 5" are independent.
    rng = random.Random(f"{scenario}:{seed}")
    profile = (profile_fn or SCENARIOS[scenario])(rng)
    moves, weights = zip(*(turn_split or TURN_SPLIT).items())
    vehicles: list[Vehicle] = []
    for a in APPROACHES:
        for t0, t1, rate in profile[a]:
            t = t0
            while True:
                t += rng.expovariate(rate / 3600.0)  # exponential gap -> Poisson arrivals
                if t >= t1:
                    break
                vehicles.append(Vehicle("", round(t, 2), a, rng.choices(moves, weights)[0]))
    vehicles.sort(key=lambda v: (v.depart, v.approach))  # SUMO requires sorted departures
    return [
        Vehicle(f"{v.approach}_{v.movement[0]}_{i:04d}", v.depart, v.approach, v.movement)
        for i, v in enumerate(vehicles)
    ], profile


def write_route_file(
    path: Path, scenario: str, seed: int, profile_fn: Callable[[random.Random], Profile] | None = None,
    turn_split: dict[str, float] | None = None,
) -> dict:
    vehicles, profile = generate_vehicles(scenario, seed, profile_fn, turn_split)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f"<!-- Generated by scripts/generate_scenarios.py: scenario={scenario} seed={seed}. Do not edit. -->",
        "<!-- Rates (veh/h) per approach: "
        + "; ".join(f"{a}=" + ",".join(f"[{t0:.0f}-{t1:.0f}s {r:.0f}]" for t0, t1, r in profile[a]) for a in APPROACHES)
        + " -->",
        "<routes>",
        '    <vType id="car" accel="2.6" decel="4.5" sigma="0.5" length="5" minGap="2.5" maxSpeed="13.89"/>',
    ]
    for (a, m), b in EXIT.items():
        lines.append(f'    <route id="{a}_{m[0]}" edges="{a}2C C2{b}"/>')
    for v in vehicles:
        lines.append(
            f'    <vehicle id="{v.vid}" type="car" route="{v.approach}_{v.movement[0]}" '
            f'depart="{v.depart:.2f}" departLane="best" departSpeed="max"/>'
        )
    lines.append("</routes>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    counts = {a: sum(1 for v in vehicles if v.approach == a) for a in APPROACHES}
    return {"scenario": scenario, "seed": seed, "vehicles": len(vehicles), "per_approach": counts}
